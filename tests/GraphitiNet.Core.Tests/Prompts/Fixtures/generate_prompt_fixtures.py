"""Generate the golden prompt and schema fixtures from an upstream Graphiti checkout.

Usage (run with -I so nothing next to the upstream sources is imported):

    python3 -I generate_prompt_fixtures.py <path to graphiti_core-x.y.z> <output dir>

The script never imports or runs upstream code. It parses graphiti_core/prompts/*.py with ``ast`` and
evaluates the prompt builder functions with a small interpreter that only understands the constructs those
functions use (f-strings, string concatenation, ``context[...]``, ``context.get``, ``to_prompt_json``,
``len``, ``str.join``, ``if``/``else`` and calls to helpers in the same module). Values are formatted with
real Python semantics (``str()`` for f-string fields, ``json.dumps`` for ``to_prompt_json``), which is
exactly what the C# port must reproduce.

Response-model schemas are produced by re-declaring each upstream Pydantic model from its parsed class
definition with ``pydantic.create_model`` and calling ``model_json_schema()``.

Outputs:
    prompt_renders.json  contexts plus the system/user text of every prompt for every context
    response_schemas.json  json.dumps(model_json_schema()) for every response model
"""

from __future__ import annotations

import ast
import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

PROMPT_MODULES = [
    'extract_nodes',
    'dedupe_nodes',
    'extract_edges',
    'extract_nodes_and_edges',
    'dedupe_edges',
    'summarize_nodes',
    'summarize_sagas',
    'eval',
]

NOTICE = (
    'Generated by generate_prompt_fixtures.py from Graphiti {version} (Copyright 2024, Zep Software, Inc., '
    'Apache License 2.0). The prompt text below is upstream text.'
)


# ---------------------------------------------------------------------------------------------------------
# Context encoding shared with the C# tests: plain JSON, plus {"$datetime": "<isoformat>"} for datetimes.
# ---------------------------------------------------------------------------------------------------------


def decode(value: Any) -> Any:
    if isinstance(value, dict):
        if set(value) == {'$datetime'}:
            return datetime.fromisoformat(value['$datetime'])
        return {k: decode(v) for k, v in value.items()}
    if isinstance(value, list):
        return [decode(v) for v in value]
    return value


# ---------------------------------------------------------------------------------------------------------
# A tiny evaluator for the prompt builder functions.
# ---------------------------------------------------------------------------------------------------------


class _Return(Exception):
    def __init__(self, value: Any) -> None:
        self.value = value


def to_prompt_json(data: Any, ensure_ascii: bool = False, indent: int | None = None) -> str:
    return json.dumps(data, ensure_ascii=ensure_ascii, indent=indent)


class Module:
    def __init__(self, path: Path, globals_: dict[str, Any]) -> None:
        self.tree = ast.parse(path.read_text(encoding='utf-8'), filename=str(path))
        self.globals = dict(globals_)
        self.functions: dict[str, ast.FunctionDef] = {}
        self.classes: dict[str, ast.ClassDef] = {}
        for node in self.tree.body:
            if isinstance(node, ast.FunctionDef):
                self.functions[node.name] = node
            elif isinstance(node, ast.ClassDef):
                self.classes[node.name] = node
            elif isinstance(node, ast.Assign) and len(node.targets) == 1:
                target = node.targets[0]
                if isinstance(target, ast.Name) and target.id != 'versions':
                    try:
                        self.globals[target.id] = self.eval(node.value, {})
                    except NotImplementedError:
                        pass  # not a plain string constant; not needed by the builders

    def call(self, name: str, args: list[Any], kwargs: dict[str, Any] | None = None) -> Any:
        fn = self.functions[name]
        params = [a.arg for a in fn.args.args]
        defaults = fn.args.defaults
        local: dict[str, Any] = {}
        first_default = len(params) - len(defaults)
        for i, param in enumerate(params):
            if i < len(args):
                local[param] = args[i]
            elif kwargs and param in kwargs:
                local[param] = kwargs[param]
            else:
                local[param] = self.eval(defaults[i - first_default], {})
        try:
            self.exec_body(fn.body, local)
        except _Return as r:
            return r.value
        return None

    def exec_body(self, body: list[ast.stmt], local: dict[str, Any]) -> None:
        for stmt in body:
            if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant):
                continue  # docstring
            if isinstance(stmt, ast.Assign):
                (target,) = stmt.targets
                assert isinstance(target, ast.Name)
                local[target.id] = self.eval(stmt.value, local)
            elif isinstance(stmt, ast.AnnAssign):
                assert isinstance(stmt.target, ast.Name)
                local[stmt.target.id] = self.eval(stmt.value, local)
            elif isinstance(stmt, ast.If):
                if self.eval(stmt.test, local):
                    self.exec_body(stmt.body, local)
                else:
                    self.exec_body(stmt.orelse, local)
            elif isinstance(stmt, ast.Return):
                raise _Return(self.eval(stmt.value, local))
            else:
                raise NotImplementedError(ast.dump(stmt))

    def eval(self, node: ast.expr, local: dict[str, Any]) -> Any:
        if isinstance(node, ast.Constant):
            return node.value
        if isinstance(node, ast.JoinedStr):
            parts = []
            for value in node.values:
                if isinstance(value, ast.Constant):
                    parts.append(value.value)
                else:
                    assert isinstance(value, ast.FormattedValue)
                    if value.conversion != -1 or value.format_spec is not None:
                        raise NotImplementedError(ast.dump(value))
                    parts.append(format(self.eval(value.value, local), ''))
            return ''.join(parts)
        if isinstance(node, ast.Name):
            if node.id in local:
                return local[node.id]
            if node.id in self.globals:
                return self.globals[node.id]
            if node.id in ('True', 'False', 'None'):
                return {'True': True, 'False': False, 'None': None}[node.id]
            raise NotImplementedError(f'name {node.id}')
        if isinstance(node, ast.Subscript):
            return self.eval(node.value, local)[self.eval(node.slice, local)]
        if isinstance(node, ast.BinOp):
            left, right = self.eval(node.left, local), self.eval(node.right, local)
            if isinstance(node.op, ast.Add):
                return left + right
            if isinstance(node.op, ast.Sub):
                return left - right
            raise NotImplementedError(ast.dump(node))
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not):
            return not self.eval(node.operand, local)
        if isinstance(node, ast.IfExp):
            return self.eval(node.body if self.eval(node.test, local) else node.orelse, local)
        if isinstance(node, ast.List):
            return [self.eval(e, local) for e in node.elts]
        if isinstance(node, ast.ListComp):
            (gen,) = node.generators
            assert not gen.ifs and isinstance(gen.target, ast.Name)
            assert isinstance(node.elt, ast.Name) and node.elt.id == gen.target.id
            return list(self.eval(gen.iter, local))
        if isinstance(node, ast.Call):
            args = [self.eval(a, local) for a in node.args]
            kwargs = {k.arg: self.eval(k.value, local) for k in node.keywords}
            func = node.func
            if isinstance(func, ast.Name):
                if func.id == 'to_prompt_json':
                    return to_prompt_json(*args, **kwargs)
                if func.id == 'len':
                    return len(*args)
                if func.id == 'Message':
                    return {'role': kwargs['role'], 'content': kwargs['content']}
                if func.id in self.functions:
                    return self.call(func.id, args, kwargs)
            if isinstance(func, ast.Attribute):
                owner = self.eval(func.value, local)
                if func.attr == 'get' and isinstance(owner, dict):
                    return owner.get(*args)
                if func.attr == 'join' and isinstance(owner, str):
                    return owner.join(*args)
            raise NotImplementedError(ast.dump(node))
        raise NotImplementedError(ast.dump(node))


def load_prompt_modules(upstream: Path) -> dict[str, Module]:
    prompts = upstream / 'graphiti_core' / 'prompts'
    text_utils = Module(upstream / 'graphiti_core' / 'utils' / 'text_utils.py', {})
    base = {'MAX_SUMMARY_CHARS': text_utils.globals['MAX_SUMMARY_CHARS']}
    snippets = Module(prompts / 'snippets.py', base)
    base['summary_instructions'] = snippets.globals['summary_instructions']
    return {name: Module(prompts / f'{name}.py', base) for name in PROMPT_MODULES}


def prompt_groups(upstream: Path) -> dict[str, list[str]]:
    tree = ast.parse((upstream / 'graphiti_core' / 'prompts' / 'lib.py').read_text(encoding='utf-8'))
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, 'id', None) == 'PROMPT_GROUPS':
            return ast.literal_eval(node.value)
    raise RuntimeError('PROMPT_GROUPS not found')


# ---------------------------------------------------------------------------------------------------------
# Response-model schemas.
# ---------------------------------------------------------------------------------------------------------


def build_models(modules: dict[str, Module]) -> dict[str, Any]:
    from pydantic import BaseModel, Field, create_model

    models: dict[str, Any] = {}

    def annotation(node: ast.expr) -> Any:
        if isinstance(node, ast.Name):
            return {'str': str, 'int': int, 'bool': bool, 'float': float}.get(node.id) or models[node.id]
        if isinstance(node, ast.Subscript) and getattr(node.value, 'id', None) == 'list':
            return list[annotation(node.slice)]  # type: ignore[misc]
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
            return annotation(node.left) | annotation(node.right)
        if isinstance(node, ast.Constant) and node.value is None:
            return type(None)
        raise NotImplementedError(ast.dump(node))

    for module in modules.values():
        for cls in module.classes.values():
            if not any(getattr(b, 'id', None) == 'BaseModel' for b in cls.bases):
                continue
            fields: dict[str, Any] = {}
            doc = ast.get_docstring(cls, clean=True)
            for stmt in cls.body:
                if not isinstance(stmt, ast.AnnAssign):
                    continue
                name = stmt.target.id  # type: ignore[union-attr]
                ann = annotation(stmt.annotation)
                value = stmt.value
                if value is None:
                    fields[name] = (ann, ...)
                    continue
                assert isinstance(value, ast.Call) and getattr(value.func, 'id', None) == 'Field'
                kwargs: dict[str, Any] = {}
                for kw in value.keywords:
                    if kw.arg == 'default_factory':
                        assert isinstance(kw.value, ast.Lambda)
                        literal = ast.literal_eval(kw.value.body)
                        kwargs['default_factory'] = lambda literal=literal: list(literal)
                    else:
                        kwargs[kw.arg] = module.eval(kw.value, {})
                if value.args:
                    first = value.args[0]
                    if not (isinstance(first, ast.Constant) and first.value is Ellipsis):
                        kwargs['default'] = module.eval(first, {})
                fields[name] = (ann, Field(**kwargs))
            model = create_model(cls.name, __base__=BaseModel, **fields)
            if doc:
                model.__doc__ = doc
                model.model_rebuild(force=True)
            models[cls.name] = model
    return models


def main() -> None:
    upstream = Path(sys.argv[1])
    out = Path(sys.argv[2])
    version = upstream.name.split('-')[-1]
    modules = load_prompt_modules(upstream)
    groups = prompt_groups(upstream)
    contexts = json.loads((out / 'prompt_contexts.json').read_text(encoding='utf-8'))

    renders: dict[str, Any] = {}
    for context_name, encoded in contexts['contexts'].items():
        context = decode(encoded)
        renders[context_name] = {}
        for group, functions in groups.items():
            for function in functions:
                messages = modules[group].call(function, [context])
                assert [m['role'] for m in messages] == ['system', 'user']
                renders[context_name][f'{group}.{function}'] = {
                    'system': messages[0]['content'],
                    'user': messages[1]['content'],
                }

    (out / 'prompt_renders.json').write_text(
        json.dumps({'_notice': NOTICE.format(version=version), 'renders': renders}, ensure_ascii=False, indent=1)
        + '\n',
        encoding='utf-8',
    )

    import pydantic

    models = build_models(modules)
    schemas = {name: json.dumps(model.model_json_schema()) for name, model in models.items()}
    (out / 'response_schemas.json').write_text(
        json.dumps(
            {
                '_notice': NOTICE.format(version=version) + f' Schemas from pydantic {pydantic.VERSION}.',
                'schemas': schemas,
            },
            ensure_ascii=False,
            indent=1,
        )
        + '\n',
        encoding='utf-8',
    )


if __name__ == '__main__':
    main()
